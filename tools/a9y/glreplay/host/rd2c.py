#!/usr/bin/env python3
"""Turn a freedreno .rd(.gz) capture (one submit, FD_RD_DUMP=full) into a C header for a9yreplay.

  rd2c.py CAPTURE.rd.gz RT_IOVA RT_W RT_H RT_PITCH > capture.h

Every buffer keeps its captured GPU address; its contents go in as runs of non-zero dwords,
so the mostly empty buffers cost nothing. The render target is described for the read-back.
"""
import struct, sys

sys.path.insert(0, __import__('os').path.dirname(__file__))
from rdlist import sections


def runs(body):
    dw = struct.unpack('<%dI' % (len(body) // 4), body[:len(body) // 4 * 4])
    out, i = [], 0
    while i < len(dw):
        if dw[i] == 0:
            i += 1
            continue
        j = i
        while j < len(dw) and (dw[j] != 0 or (j + 1 < len(dw) and dw[j + 1] != 0)):
            j += 1
        out.append((i, dw[i:j]))
        i = j
    return out


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    path = sys.argv[1]
    rt_iova, rt_w, rt_h, rt_pitch = (int(a, 0) for a in sys.argv[2:])
    bufs, ib, gpuaddr = [], None, None
    for typ, body in sections(path):
        if typ == 3:
            lo, size = struct.unpack_from('<II', body)
            hi = struct.unpack_from('<I', body, 8)[0] if len(body) >= 12 else 0
            gpuaddr = (hi << 32 | lo, size)
        elif typ == 12:
            bufs.append((gpuaddr[0], gpuaddr[1], runs(body)))
        elif typ == 6:
            lo, dw = struct.unpack_from('<II', body)
            hi = struct.unpack_from('<I', body, 8)[0] if len(body) >= 12 else 0
            if ib is not None:
                sys.exit('more than one cmdstream: capture a single submit')
            ib = (hi << 32 | lo, dw)
    if ib is None:
        sys.exit('no cmdstream in capture')

    print('/* generated by rd2c.py from %s */' % path.split('/')[-1])
    print('#define CAP_IB_IOVA 0x%xull' % ib[0])
    print('#define CAP_IB_DWORDS %d' % ib[1])
    print('#define CAP_RT_IOVA 0x%xull' % rt_iova)
    print('#define CAP_RT_W %d' % rt_w)
    print('#define CAP_RT_H %d' % rt_h)
    print('#define CAP_RT_PITCH %d' % rt_pitch)
    print('static const uint32_t cap_data[] = {')
    off = 0
    meta = []
    for b, (iova, size, rs) in enumerate(bufs):
        first = len(meta)
        for start, vals in rs:
            meta.append((start, len(vals), off))
            for k in range(0, len(vals), 8):
                print('\t' + ', '.join('0x%08x' % v for v in vals[k:k + 8]) + ',')
            off += len(vals)
        bufs[b] = (iova, size, first, len(meta) - first)
    print('};')
    print('static const struct cap_run { uint32_t dword, count, data; } cap_runs[] = {')
    for m in meta:
        print('\t{ %d, %d, %d },' % m)
    print('};')
    print('static const struct cap_buf { uint64_t iova; uint32_t bytes, run, nruns; } cap_bufs[] = {')
    for iova, size, first, n in bufs:
        print('\t{ 0x%xull, 0x%x, %d, %d },' % (iova, size, first, n))
    print('};')


if __name__ == '__main__':
    main()
