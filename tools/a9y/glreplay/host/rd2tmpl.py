#!/usr/bin/env python3
"""Turn a freedreno .rd(.gz) capture of fit.c (one submit) into the kernel's present template (C header).

  rd2tmpl.py CAPTURE.rd.gz SRC_IOVA DST_IOVA > sweet_a5xx_fit.h

SRC_IOVA and DST_IOVA are the captured texture and render target (cffdump: TEX_CONST BASE, RB_MRT[0].BASE). Every
other buffer goes into one template, 4K-aligned in capture order, with the command stream among them. Each 64-bit
address in the template (a low dword inside a captured buffer, a high dword whose low byte is the capture's 0x10)
becomes a relocation: against the template itself, the source frame or the panel, each plus an offset. The kernel
expands the runs once, relocates, and per frame repoints only the source.
"""
import struct, sys

sys.path.insert(0, __import__('os').path.dirname(__file__))
from rdlist import sections
from rd2c import runs

KINDS = ('A5FIT_SELF', 'A5FIT_SRC', 'A5FIT_DST')


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path = sys.argv[1]
    src, dst = int(sys.argv[2], 0), int(sys.argv[3], 0)
    bufs, ib, gpuaddr = [], None, None
    for typ, body in sections(path):
        if typ == 3:
            lo, size = struct.unpack_from('<II', body)
            hi = struct.unpack_from('<I', body, 8)[0] if len(body) >= 12 else 0
            gpuaddr = (hi << 32 | lo, size)
        elif typ == 12:
            bufs.append((gpuaddr[0], gpuaddr[1], body))
        elif typ == 6:
            lo, dw = struct.unpack_from('<II', body)
            hi = struct.unpack_from('<I', body, 8)[0] if len(body) >= 12 else 0
            if ib is not None:
                sys.exit('more than one cmdstream: capture a single submit')
            ib = (hi << 32 | lo, dw)
    if ib is None:
        sys.exit('no cmdstream in capture')
    big = {b[0]: b for b in bufs if b[0] in (src, dst)}
    if len(big) != 2:
        sys.exit('source or target not among the captured buffers')

    # the template: the small buffers, 4K-aligned
    place, off = [], 0
    for iova, size, body in bufs:
        if iova in big:
            continue
        place.append((iova, size, off, body))
        off += (size + 0xfff) & ~0xfff
    total = off
    tmpl = bytearray(total)
    for iova, size, o, body in place:
        tmpl[o:o + len(body)] = body

    def target(addr):
        for iova, size, o, _ in place:
            if iova <= addr < iova + size:
                return 0, o + addr - iova
        for kind, base in ((1, src), (2, dst)):
            if base <= addr < base + big[base][1]:
                return kind, addr - base
        return None

    dw = list(struct.unpack('<%dI' % (total // 4), bytes(tmpl)))
    relocs = []
    for i in range(len(dw) - 1):
        lo, hi = dw[i], dw[i + 1]
        if lo == 0 or (hi & 0xff) != 0x10:
            continue
        t = target(0x1000000000 | lo)
        if t is None:
            continue
        relocs.append((i, i + 1, t[0], t[1]))
        dw[i] = 0
        dw[i + 1] = hi & ~0xff
    ib_off = target(ib[0])
    if ib_off is None or ib_off[0] != 0:
        sys.exit('cmdstream outside the template')
    for i, h, kind, add in relocs:
        sys.stderr.write('reloc dword 0x%05x -> %s + 0x%x\n' % (i * 4, KINDS[kind], add))

    body = struct.pack('<%dI' % len(dw), *dw)
    print('/* generated by tools/a9y/glreplay/host/rd2tmpl.py from %s (tools/a9y/glreplay/host/fit.c) */'
          % path.split('/')[-1])
    print('#define A5FIT_BYTES 0x%x' % total)
    print('#define A5FIT_IB_OFF 0x%x' % ib_off[1])
    print('#define A5FIT_IB_DWORDS %d' % ib[1])
    print('enum { %s };' % ', '.join(KINDS))
    print('static const uint32_t a5fit_data[] = {')
    meta, n = [], 0
    for start, vals in runs(body):
        meta.append((start, len(vals), n))
        for k in range(0, len(vals), 8):
            print('\t' + ', '.join('0x%08x' % v for v in vals[k:k + 8]) + ',')
        n += len(vals)
    print('};')
    print('static const struct a5fit_run { uint32_t dword, count, data; } a5fit_runs[] = {')
    for m in meta:
        print('\t{ %d, %d, %d },' % m)
    print('};')
    print('/* lo and hi dwords of each address: the target\'s base plus add, its high half or-ed into hi */')
    print('static const struct a5fit_reloc { uint32_t lo, hi, kind, add; } a5fit_relocs[] = {')
    for i, h, kind, add in relocs:
        print('\t{ %d, %d, %s, 0x%x },' % (i, h, KINDS[kind], add))
    print('};')


if __name__ == '__main__':
    main()
